"""Reproducible engine latency gate for PLAN.md section 8.

AC-016: p95 engine compute time (excluding network/serialization) is under
5ms at 1 scenario, 50ms at 100, 250ms at 1,000 and 2s at 10,000, each with
K=200 sensitivity draws.
"""

from __future__ import annotations

import argparse
import platform
import time
from pathlib import Path

import numpy as np

from backend.engine.batch import evaluate_batch
from backend.engine.scenario import Lever, Scenario
from backend.model.spec import build_param_draws

BUDGET_MS = {1: 5.0, 100: 50.0, 1_000: 250.0, 10_000: 2_000.0}


def measure(sizes: list[int], repeats: int) -> list[dict[str, float | int | bool]]:
    draws = build_param_draws(k=200, seed=42)
    rows = []
    for size in sizes:
        # Every scenario is distinct (can price x PET price grid, 0.95-1.05) so the engine's
        # duplicate-scenario shortcut cannot flatter the larger sizes, and the grid sits inside the
        # supported range: this gates interactive in-range use. Refused scenarios take a slower path
        # (a nearest-supported suggestion is built for each) and are timed separately, see
        # `measure_refusal_heavy`.
        scenarios = [
            Scenario(levers={
                "Aurora-can_330ml": Lever(price_index=round(0.95 + (i % 101) * 0.001, 3)),
                "Aurora-pet_500ml": Lever(price_index=round(0.95 + (i // 101) * 0.001, 3)),
            })
            for i in range(size)
        ]
        evaluate_batch(scenarios[:1], draws)  # warm imports and cached baseline
        samples = []
        for _ in range(repeats):
            start = time.perf_counter()
            evaluate_batch(scenarios, draws)
            samples.append((time.perf_counter() - start) * 1000.0)
        p95 = float(np.percentile(samples, 95))
        rows.append(
            {
                "scenarios": size,
                "p95_ms": p95,
                "best_ms": min(samples),
                "worst_ms": max(samples),
                "budget_ms": BUDGET_MS[size],
                "pass": p95 < BUDGET_MS[size],
            }
        )
    return rows


def render(rows: list[dict[str, float | int | bool]], repeats: int) -> str:
    lines = [
        "# Engine performance benchmark",
        "",
        f"Generated by `uv run python benchmarks/bench_engine.py` with {repeats} timed runs per size.",
        "",
        f"Environment: Python {platform.python_version()}, NumPy {np.__version__}, {platform.platform()}.",
        "Warm-up and model draw construction are excluded; cached baseline/envelope setup is excluded.",
        "Each evaluation uses K=200 draws and a fixed seed (42).",
        "",
        "| Scenarios | p95 (ms) | Best (ms) | Worst (ms) | Budget (ms) | Result |",
        "|---:|---:|---:|---:|---:|:---:|",
    ]
    for row in rows:
        lines.append(
            f"| {row['scenarios']:,} | {row['p95_ms']:.2f} | {row['best_ms']:.2f} | "
            f"{row['worst_ms']:.2f} | <{row['budget_ms']:,.0f} | {'PASS' if row['pass'] else 'FAIL'} |"
        )
    lines.extend(
        ["", "Budgets are from PLAN.md section 8. Timing excludes HTTP and serialization.", ""]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--sizes", nargs="+", type=int, choices=sorted(BUDGET_MS), default=list(BUDGET_MS)
    )
    parser.add_argument("--repeats", type=int, default=5)
    parser.add_argument("--output", type=Path, default=Path("reports/engine_bench.md"))
    args = parser.parse_args()
    if args.repeats < 3:
        parser.error("--repeats must be at least 3")
    rows = measure(args.sizes, args.repeats)
    report = render(rows, args.repeats)
    print(report)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(report, encoding="utf-8")
    return 0 if all(bool(row["pass"]) for row in rows) else 1


if __name__ == "__main__":
    raise SystemExit(main())
